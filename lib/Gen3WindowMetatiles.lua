-- Index once, on first ask, rather than walking a list per cell.
local index = {}
local function setOf(field, game, key)
  local byGame = index[field]
  if not byGame then byGame = {}; index[field] = byGame end
  local byKey = byGame[game]
  if not byKey then
    byKey = {}
    for ts, ids in pairs((M[field] or {})[game] or {}) do
      local set = {}
      for _, id in ipairs(ids) do set[id] = true end
      byKey[ts] = set
    end
    byGame[game] = byKey
  end
  return byKey[key]
end

-- `tilesetDef` is the PAIR record a Map carries, and this reads its
-- primaryKey/secondaryKey rather than the pair's own id: the tables are keyed
-- by the INDIVIDUAL tilesets, because a secondary is shared between pairs and
-- its windows do not change when the primary it is paired with does.
local function lookup(field, game, tilesetDef, metatile)
  if not (game and tilesetDef and metatile) then return false end
  local split = M.metatilesInPrimary[game] or 512
  local key
  if metatile < split then key = tilesetDef.primaryKey
  else key = tilesetDef.secondaryKey end
  local set = key and setOf(field, game, key)
  return (set and set[metatile]) == true
end

function M.isWindow(game, tilesetDef, metatile)
  return lookup("windows", game, tilesetDef, metatile)
end

function M.isGlassDoor(game, tilesetDef, metatile)
  return lookup("doors", game, tilesetDef, metatile)
end

