-- WHICH GEN 3 METATILES ARE WINDOW GLASS.
--
-- Neither pret disassembly labels these.  pokeemerald's metatile_labels.h
-- has no `Window` macro at all, and pokefirered's only ones are Silph Co's
-- scripted elevator window (0x2E8-0x2FA) -- so there is no list to copy and
-- this one was READ OFF THE ART: every metatile of all 136 tilesets in the
-- two cartridges was composited exactly as the game draws it (two layers,
-- per-quadrant flips, the pair's own palette banks) and inspected.
--
-- A METATILE IS IN HERE IF YOU CAN SEE GLASS IN IT.  A window is normally
-- two or four cells and panes straddle cell edges, so a cell holding part of
-- a pane counts even when most of it is wall.  Frame, sill, shutter and
-- curtain cells with no glass showing are NOT here.
--
-- Deliberately excluded, because they are the things that look like glass
-- and are not: water of every kind (sea, ponds, puddles, waterfalls,
-- fountains), blue roofs, floors and carpet, TV and PC screens, the Pokemon
-- Center healing machine's display, Game Corner machines, signs, banners and
-- framed pictures, ice and crystal, and glass-fronted furniture -- a display
-- case is glass but it is not a window.
--
-- DOORS ARE SEPARATE.  A shop's glass double door is glass and is not a
-- window, so it is in `doors` rather than `windows`.
--
-- `unused` names the entries no shipped map ever places.  They are real
-- window art in the tileset -- a map editor wants them -- but a renderer
-- walking Hoenn or Kanto will never meet one, so they are marked rather than
-- dropped.  Every other id in here appears in at least one map's blockdata.
--
-- Keys are the cache's own tileset ids, and metatile ids are in the pair's
-- numbering: below metatilesInPrimary (512 Emerald, 640 FireRed) they belong
-- to the primary, at or above it to the secondary.

